#!/usr/bin/env node
/** OMH runtime CLI: persistent tasks, workflows, memory, skills and audit. */
import {resolve,join} from 'node:path';
import {TaskQueue} from '../modules/task-queue.mjs';
import {makeHandlers} from '../modules/queue-handlers.mjs';
import {MemoryStore} from '../modules/memory.mjs';
import {WorkflowRunner} from '../modules/workflows.mjs';
import {Scheduler} from '../modules/scheduler.mjs';
import {TraceJournal} from '../modules/trace-journal.mjs';
import {publishSkill} from '../modules/skill-studio.mjs';
import {WorkspaceManager} from '../modules/workspaces.mjs';
import {AgentBus} from '../modules/agent-bus.mjs';
import {ToolPolicy} from '../modules/tool-policy.mjs';
import {SkillProposalStore} from '../modules/skill-proposals.mjs';
import {PluginRegistry} from '../modules/plugin-registry.mjs';
import {diagnose} from '../modules/doctor.mjs';
const [action,raw='{}']=process.argv.slice(2);
const workspace=resolve(process.env.OMH_WORKSPACE||process.cwd());
const state=resolve(process.env.OMH_STATE_DIR||join(workspace,'.omh'));
const handlers=makeHandlers(workspace,{stateDir:state});
const queue=await new TaskQueue(join(state,'tasks.json'),handlers).load();
const memory=await new MemoryStore(join(state,'memory.json')).load();
const scheduler=await new Scheduler(join(state,'schedules.json'),queue).load();
const workspaces=new WorkspaceManager(join(state,'team-workspaces'));
const bus=await new AgentBus(join(state,'agent-bus.json')).load();
const proposals=await new SkillProposalStore(join(state,'skill-proposals.json')).load();
const plugins=await new PluginRegistry(join(state,'plugins.json')).load();
const toolPolicy=new ToolPolicy({allow:['workspace.read'],ask:['workspace.write','sandbox.exec']});
const trace=new TraceJournal(join(state,'audit.jsonl'),{enabled:process.env.OMH_TRACE==='1'});
try {
 const data=JSON.parse(raw);
 let result;
 switch(action){
  case 'status':result={workspace,state,handlers:Object.keys(handlers),queued:queue.list().filter(t=>t.status==='queued').length,scheduled:scheduler.list().length,traceEnabled:trace.enabled};break;
  case 'doctor':result=await diagnose();break;
  case 'task:add':result=await queue.enqueue(data.kind,data.input);await trace.record('task.queued',{id:result.id,kind:result.kind});break;
  case 'task:run':await trace.record('task.started',{});result=await queue.runNext();await trace.record('task.finished',{id:result?.id,status:result?.status,error:result?.error});for(const event of result?.result?.events||[])await trace.record('agent.event',event);break;
  case 'task:list':result=queue.list();break;
  case 'task:cancel':result=await queue.cancel(data.id);break;
  case 'task:retry':result=await queue.retry(data.id,{maxAttempts:data.maxAttempts??3});break;
  case 'workflow:run':await trace.record('workflow.started',{name:data.name});result=await new WorkflowRunner(queue).executeSequential(data);await trace.record('workflow.finished',{name:data.name,statuses:result.results.map(x=>x.status)});break;
  case 'workflow:submit':result=await new WorkflowRunner(queue).submit(data);break;
  case 'memory:add':result=await memory.add(data);await trace.record('memory.updated',{id:result.id});break;
  case 'memory:list':result=memory.list(data);break;
  case 'memory:search':result=memory.search(data.query,data);break;
  case 'memory:remove':result={removed:await memory.remove(data.id)};break;
  case 'skill:publish':result=await publishSkill({...data,root:join(workspace,'skills')});await trace.record('skill.published',{name:result.name});break;
  case 'schedule:add':result=await scheduler.add(data);break;
  case 'schedule:tick':result=await scheduler.tick();break;
  case 'schedule:list':result=scheduler.list();break;
  case 'trace:list':result=await trace.read(data);break;
  case 'workspace:create':result={path:await workspaces.create(data.id)};break;
  case 'workspace:list':result=await workspaces.list();break;
  case 'workspace:snapshot':result={path:await workspaces.snapshot(data.id,data.snapshotId)};break;
  case 'workspace:restore':result={path:await workspaces.restore(data.id,data.snapshotId,{approved:data.approved})};break;
  case 'agent:send':result=await bus.send(data);break;
  case 'agent:inbox':result=bus.inbox(data.agent);break;
  case 'agent:ack':result={acknowledged:await bus.ack(data.agent,data.id)};break;
  case 'tool:check':result=toolPolicy.check(data.name,{approved:data.approved});break;
  case 'skill:propose':result=await proposals.propose(data);break;
  case 'skill:proposals':result=proposals.list(data.status);break;
  case 'skill:review':result=await proposals.review(data.id,{decision:data.decision,approved:data.approved,root:join(workspace,'skills')});break;
  case 'plugin:register':result=await plugins.register(data);break;
  case 'plugin:enable':result=await plugins.enable(data.name,{approved:data.approved});break;
  case 'plugin:disable':result=await plugins.disable(data.name);break;
  case 'plugin:list':result=plugins.list();break;
  case 'plugin:capabilities':result=plugins.allowedCapabilities();break;
  default:throw new Error('Usage: node scripts/omh-runtime.mjs status | doctor | task:add | task:run | task:list | task:cancel | task:retry | workflow:run | workflow:submit | memory:add | memory:list | memory:search | memory:remove | skill:publish | schedule:add | schedule:tick | schedule:list | trace:list | workspace:create | workspace:list | workspace:snapshot | workspace:restore | agent:send | agent:inbox | agent:ack | tool:check | skill:propose | skill:proposals | skill:review | plugin:register | plugin:enable | plugin:disable | plugin:list | plugin:capabilities [JSON]');
 }
 process.stdout.write(JSON.stringify(result,null,2)+'\n');
} catch(error){process.stderr.write('OMH: '+error.message+'\n');process.exitCode=1;}
